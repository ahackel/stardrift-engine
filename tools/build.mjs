// node tools/build.mjs — what is made from src/ (the tests check both are current):
//   dist/worklet.js        the AudioWorklet with the engine inlined, one file with no imports, so a bundler (Vite,
//                          webpack) that copies it as an asset still gets a worklet that runs
//   dist/song.schema.json  the song format as a JSON Schema (src/schema.js)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

import { songSchema } from '../src/schema.js';

const SRC = new URL('../src/', import.meta.url), DIST = new URL('../dist/', import.meta.url);
const IMPORT = /^import \{([^}]*)\} from '(\.[^']+)';\n/gm;

// each module in the order it is needed, wrapped in a function so their top-level names never clash
export async function bundle(entry = 'worklet.js') {
  const done = new Set(), parts = [];
  const varOf = (url) => '$' + url.href.slice(SRC.href.length).replace(/\.js$/, '').replace(/\W/g, '_');
  const imports = (code, url) => [...code.matchAll(IMPORT)].map(([, names, path]) => {
    const dep = new URL(path, url);
    return { dep, line: `const {${names.replace(/ as /g, ': ')}} = ${varOf(dep)};` };
  });
  async function add(url, isEntry) {
    if (done.has(url.href)) return;
    done.add(url.href);
    const code = readFileSync(url, 'utf8'), deps = imports(code, url);
    for (const { dep } of deps) await add(dep, false);
    let body = code.replace(IMPORT, '');
    if (/^import /m.test(body)) throw new Error(`${url.pathname}: only "import { … } from './…'" can be inlined`);
    const head = deps.map((d) => d.line).join('\n');
    if (isEntry) { parts.push(`${head}\n${body}`); return; }
    body = body.replace(/^export (?=(async )?(function|const|let|class) )/gm, '');
    if (/^export /m.test(body)) throw new Error(`${url.pathname}: only exported declarations can be inlined`);
    const names = Object.keys(await import(url.href));
    parts.push(`const ${varOf(url)} = (() => {\n${head}\n${body}\nreturn { ${names.join(', ')} };\n})();`);
  }
  await add(new URL(entry, SRC), true);
  return `// Generated by tools/build.mjs from src/ (npm run build): edit src/, not this file.\n${parts.join('\n\n')}`;
}

export const built = async () => ({ 'worklet.js': await bundle(), 'song.schema.json': `${JSON.stringify(songSchema(), null, 2)}\n` });

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(DIST, { recursive: true });
  for (const [name, text] of Object.entries(await built())) {
    writeFileSync(new URL(name, DIST), text);
    console.log(`dist/${name} (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
